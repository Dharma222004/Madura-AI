import { describe, it, expect, vi } from 'vitest';
import { imageModelRouter } from '../src/server/services/image_router.service.js';
import { ImageService } from '../src/server/services/image.service.js';
import { getImageModelRegistry } from '../src/server/config/image_models.config.js';

describe('Automatic Image Model Routing & UI Neutrality', () => {
  const imageService = new ImageService();

  describe('1. Automatic Image Model Selection (Rules Engine)', () => {
    it('should route "lion" or "a photo of a lion" to the realistic model', async () => {
      const result1 = await imageModelRouter.select('lion');
      expect(result1.primaryModel.id).toBe('cf-flux-2-klein-9b');
      expect(result1.primaryModel.strengths).toContain('photorealistic');

      const result2 = await imageModelRouter.select('a photo of a lion in savanna');
      expect(result2.primaryModel.id).toBe('cf-flux-2-klein-9b');
      expect(result2.reason).toBe('rule');
    });

    it('should route "anime girl with umbrella" to the stylized model', async () => {
      const result = await imageModelRouter.select('anime girl with umbrella');
      expect(result.primaryModel.id).toBe('oxlo-sd-1.5');
      expect(result.primaryModel.strengths).toContain('anime');
      expect(result.reason).toBe('rule');
    });

    it('should route "logo with the text \'Madura AI\'" to the text-capable model', async () => {
      const result = await imageModelRouter.select("logo with the text 'Madura AI'");
      expect(result.primaryModel.id).toBe('cf-flux-2-klein-9b');
      expect(result.primaryModel.strengths).toContain('text');
      expect(result.reason).toBe('rule');
    });

    it('should route "quick sketch of a house" to the fast model', async () => {
      const result = await imageModelRouter.select('quick sketch of a house');
      expect(result.primaryModel.id).toBe('cf-flux-2-klein-4b');
      expect(result.primaryModel.speed).toBe('fast');
      expect(result.reason).toBe('rule');
    });

    it('should route image edit / inpaint requests to edit-capable model', async () => {
      const result = await imageModelRouter.select('remove background and replace with beach');
      expect(result.primaryModel.supportsImageEdit).toBe(true);
      expect(result.primaryModel.id).toBe('cf-flux-2-klein-9b');
    });
  });

  describe('2. Fallback Chain & Resilience', () => {
    it('should fall back to next model and succeed when upstream fails (403/timeout)', async () => {
      // Mock global fetch to simulate first model failure (403 Forbidden) on Cloudflare
      const originalFetch = globalThis.fetch;
      let callCount = 0;

      globalThis.fetch = vi.fn().mockImplementation(async (url: any, opts: any) => {
        callCount++;
        const urlStr = String(url);
        // Fail Cloudflare endpoint with 403
        if (urlStr.includes('api.cloudflare.com')) {
          return new Response(JSON.stringify({ error: 'Forbidden' }), { status: 403 });
        }
        // Return success for fallback
        return originalFetch(url, opts);
      });

      try {
        const result = await imageService.generateImage('quick sketch of a house');
        expect(result.imageUrl).toBeDefined();
        expect(result.imageUrl).toContain('pollinations.ai');
        expect(callCount).toBeGreaterThan(0);
      } finally {
        globalThis.fetch = originalFetch;
      }
    });
  });

  describe('3. UI & API Model Masking (Neutral Branding)', () => {
    it('should never expose any model or provider name in client-facing output', async () => {
      const result = await imageService.generateImage('generate a photorealistic photo of sunset over snowy mountains');

      // 1. Model field must be neutral
      expect(result.model).toBe('Madura AI');
      expect(result.model).not.toContain('flux');
      expect(result.model).not.toContain('stable-diffusion');
      expect(result.model).not.toContain('cloudflare');
      expect(result.model).not.toContain('@cf');

      // 2. Markdown output must use neutral branding
      expect(result.markdownContent).toContain('*Generated by **Madura AI***');
      expect(result.markdownContent).not.toContain('flux-2-klein');
      expect(result.markdownContent).not.toContain('flux-3-image-klein');
      expect(result.markdownContent).not.toContain('stable-diffusion');
      expect(result.markdownContent).not.toContain('Cloudflare Workers AI');

      // 3. Prompt label is preserved cleanly
      expect(result.prompt).toBe('sunset over snowy mountains');

      // 4. Dimensions provided
      expect(result.dimensions).toBeDefined();
      expect(result.dimensions.width).toBeGreaterThanOrEqual(512);
      expect(result.dimensions.height).toBeGreaterThanOrEqual(512);
    });

    it('should not contain provider or model leaks in image alt text or markdown tags', async () => {
      const result = await imageService.generateImage('anime hero with sword');
      // Alt text should be the subject, not model name
      expect(result.markdownContent.startsWith('![anime hero with sword]')).toBe(true);
      expect(result.markdownContent).not.toContain('oxlo');
      expect(result.markdownContent).not.toContain('stable-diffusion');
    });
  });
});
